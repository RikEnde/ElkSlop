        k("CLG", 0xDA, 0x01), k("CLS", 0xDB, 0x01), k("COS", 0x9B, 0x00), k("COUNT", 0x9C, 0x01),
        k("DATA", 0xDC, 0x20), k("DEG", 0x9D, 0x00), k("DEF", 0xDD, 0x00), k("DELETE", 0xC7, 0x10),
        k("DIV", 0x81, 0x00), k("DIM", 0xDE, 0x02), k("DRAW", 0xDF, 0x02), k("ENDPROC", 0xE1, 0x01),
        k("END", 0xE0, 0x01), k("ENVELOPE", 0xE2, 0x02), k("ELSE", 0x8B, 0x14), k("EVAL", 0xA0, 0x00),
        k("ERL", 0x9E, 0x01), k("ERROR", 0x85, 0x04), k("EOF", 0xC5, 0x01), k("EOR", 0x82, 0x00),
