package elkslop.devkit

/**
 * BBC BASIC II's keywords, in the order its tokeniser tries them: the first
 * that fits wins, so `ENDPROC` comes before `END`, and an abbreviation such as
 * `P.` means the first keyword starting with P, `PRINT`. The order, tokens and
 * flags are BASIC II's; `BasicKeywordsTest` checks them against the ROM's own table.
 */
internal object BasicKeywords {
    class Keyword(val text: String, val token: Int, val flags: Int)

    /** Not tokenised when a letter, digit, `_` or `` ` `` follows, so `COUNTER` stays a name. */
    const val CONDITIONAL = 0x01

    /** What follows is the middle of a statement. */
    const val MIDDLE = 0x02

    /** What follows starts a statement, as after `THEN`. */
    const val START = 0x04

    /** `FN` and `PROC`: the name after them stays as it is. */
    const val FN_PROC = 0x08

    /** Numbers after it are line numbers, as after `GOTO`, and are encoded. */
    const val LINE_NUMBER = 0x10

    /** The rest of the line stays as it is, as after `REM`. */
    const val REST_OF_LINE = 0x20

    /** A pseudo-variable, such as `TIME`: at the start of a statement, where it is assigned to, the token is &40 higher. */
    const val PSEUDO_VARIABLE = 0x40

    val all: List<Keyword> = listOf(
        k("AND", 0x80, 0x00), k("ABS", 0x94, 0x00), k("ACS", 0x95, 0x00), k("ADVAL", 0x96, 0x00),
        k("ASC", 0x97, 0x00), k("ASN", 0x98, 0x00), k("ATN", 0x99, 0x00), k("AUTO", 0xC6, 0x10),
